clear;
clc;
close all;

%% Read data

OH = readtable('OHEMA.csv');
Oho = table2array(OH(:,1)).*2.74;

SD = readtable('SDEMA.csv');
SDo = table2array(SD(:,1)).*2.74;

ohfit = load('OHfitcase.mat');
sdfit = load('SDfitcase.mat');

%% Please modify these two variable names if needed
OHpred = ohfit.newcase;
SDpred = sdfit.newcase;

%% Time axis

startDate = datetime(2013,9,30);

dateOH = startDate + calweeks(0:310);
dateSD = startDate + calweeks(0:310);

yearTicks = datetime(2014:2019,1,1);

%% Plot style

fontName       = 'Times New Roman';
fontSizeTick   = 9;
fontSizeLabel  = 10;
fontSizePanel  = 13;
fontSizeLegend = 9;

obsColor = [0.80 0.30 0.20];
fitColor = [0.16 0.45 0.68];

markerSize = 4.0;
fitLineWidth = 1.8;
axisLineWidth = 0.8;

figWidth  = 17.5;
figHeight = 7.5;

%% Figure

fig = figure( ...
    'Color','w', ...
    'Units','centimeters', ...
    'Position',[2 2 figWidth figHeight]);

tl = tiledlayout(fig,1,2, ...
    'TileSpacing','compact', ...
    'Padding','compact');

%% (a) OH

%% (a) OH

ax1 = nexttile(tl,1);
hold(ax1,'on');

hObs1 = plot(ax1, ...
    dateOH, Oho(1:311), ...
    'o', ...
    'LineStyle','none', ...
    'MarkerSize',markerSize, ...
    'MarkerEdgeColor',obsColor, ...
    'MarkerFaceColor',obsColor);

hFit1 = plot(ax1, ...
    dateOH, OHpred, ...
    '-', ...
    'Color',fitColor, ...
    'LineWidth',fitLineWidth);

ylabel(ax1, ...
    'Estimated influenza cases', ...
    'FontName',fontName, ...
    'FontSize',fontSizeLabel);

xlabel(ax1, ...
    'Year', ...
    'FontName',fontName, ...
    'FontSize',fontSizeLabel);

text(ax1,0.03,0.95,'(a) OH', ...
    'Units','normalized', ...
    'FontName',fontName, ...
    'FontSize',fontSizePanel, ...
    'FontWeight','bold', ...
    'HorizontalAlignment','left', ...
    'VerticalAlignment','top');

lgd1 = legend(ax1, ...
    [hObs1,hFit1], ...
    {'Real data','Fitting curve'}, ...
    'FontName',fontName, ...
    'FontSize',fontSizeLegend, ...
    'Box','off');

lgd1.Units = 'normalized';
lgd1.Position = [0.32 0.82 0.16 0.10];
ylim([0 700])
hold(ax1,'off');

%% (b) SD

ax2 = nexttile(tl,2);
hold(ax2,'on');

hObs2 = plot(ax2, ...
    dateSD, SDo(1:311), ...
    'o', ...
    'LineStyle','none', ...
    'MarkerSize',markerSize, ...
    'MarkerEdgeColor',obsColor, ...
    'MarkerFaceColor',obsColor);

hFit2 = plot(ax2, ...
    dateSD, SDpred, ...
    '-', ...
    'Color',fitColor, ...
    'LineWidth',fitLineWidth);

ylabel(ax2, ...
    'Estimated influenza cases', ...
    'FontName',fontName, ...
    'FontSize',fontSizeLabel);

xlabel(ax2, ...
    'Year', ...
    'FontName',fontName, ...
    'FontSize',fontSizeLabel);

text(ax2,0.03,0.95,'(b) SD', ...
    'Units','normalized', ...
    'FontName',fontName, ...
    'FontSize',fontSizePanel, ...
    'FontWeight','bold', ...
    'HorizontalAlignment','left', ...
    'VerticalAlignment','top');
lgd = legend(ax2, ...
    [hObs2,hFit2], ...
   {'Real data','Fitting curve'}, ...
    'FontName',fontName, ...
    'FontSize',fontSizeLegend, ...
    'Box','off');

lgd.Units = 'normalized';
lgd.Position = [0.79 0.82 0.16 0.10];
ylim([0 300])
hold(ax2,'off');

%% Common axis style

axAll = [ax1 ax2];

for i = 1:2
    axAll(i).FontName = fontName;
    axAll(i).FontSize = fontSizeTick;
    axAll(i).LineWidth = axisLineWidth;
    axAll(i).TickDir = 'out';
    axAll(i).Box = 'off';

    axAll(i).XGrid = 'off';
    axAll(i).YGrid = 'on';
    axAll(i).GridAlpha = 0.10;

    xticks(axAll(i),yearTicks);
    xtickformat(axAll(i),'yyyy');
end

%% Export

drawnow;

exportgraphics(fig, ...
    'Figure9.eps', ...
    'ContentType','vector', ...
    'BackgroundColor','white');