clc;
clear;
close all;

%% =========================================================
% Figure: symbolic regression function + beta(t) comparisons
% (a) response function slices
% (b) IA beta(t)
% (c) IL beta(t)
% (d) IN beta(t)
% ==========================================================

%% 1. Plotting parameters

fontName       = 'Times New Roman';
fontSizeTick   = 9;
fontSizeLabel  = 10;
fontSizePanel  = 13;
fontSizeLegend = 9;

axisLineWidth  = 0.8;
mainLineWidth  = 1;
funcLineWidth  = 2.0;

% Stronger cool-warm contrast
curveColors = [ ...
    0.16 0.39 0.74   % dT = -10/30
    0.41 0.64 0.89   % dT = -5/30
    0.45 0.45 0.45   % dT =  0
    0.93 0.63 0.30   % dT =  5/30
    0.78 0.22 0.18   % dT = 10/30
];

% beta(t) comparison colors
betaBaseColor = [0.10 0.50 0.60];   % UDE / baseline beta(t), cool
betaFitColor  = [0.85 0.38 0.18];   % symbolic reconstruction, warm

figWidth  = 18.0;   % cm
figHeight = 13.0;   % cm

%% 2. Panel (a): symbolic regression function

% T range
T = linspace(-27, 31, 200);

% fixed dT values
dT_values = [-9/30, -6/30, 0/30, 6/30, 9/30];

% function values
Y = zeros(length(dT_values), length(T));

for i = 1:length(dT_values)
    dT = dT_values(i);
    Y(i,:) = exp(1.0408957382 .* ...
        (0.0000057972.*T.^3 ...
        -0.0011048007.*T.^2 ...
        +0.0050645368.*T ...
        -0.4386011040.*dT ...
        +0.1641361835)) ./ 7;
end

%% 3. Read beta data

IA = readtable("IAbeta.csv");
IL = readtable("ILbeta.csv");
IN = readtable("INbeta.csv");

IAbaseline = table2array(IA(:,2));
ILbaseline = table2array(IL(:,2));
INbaseline = table2array(IN(:,2));

IAfit = load('IAbetafit.mat');
ILfit = load('ILbetafit.mat');
INfit = load('INbetafit.mat');

% preserve your original construction
IAbeta = [IAbaseline(1:30); IAfit.beta_pred];
ILbeta = [ILbaseline(1:30); ILfit.beta_pred];
INbeta = [INbaseline(1:30); INfit.beta_pred];

% time axis
% Use this if you want consistency with earlier figures:
date1 = datetime(2013, 9, 30) + days(0:2183);

% If you want to strictly preserve the original line, replace with:
% date1 = datetime(2013, 9, 30) + days(1:2184);

yearTicks = datetime(2014:2019,1,1);

%% 4. Create figure

fig = figure( ...
    'Color','w', ...
    'Units','centimeters', ...
    'Position',[2 2 figWidth figHeight]);

tl = tiledlayout(fig,2,2, ...
    'TileSpacing','compact', ...
    'Padding','compact');

%% =========================================================
% (a) function panel
% ==========================================================

ax1 = nexttile(tl,1);
hold(ax1,'on');

for i = 1:length(dT_values)
    plot(ax1, T, Y(i,:), ...
        'LineWidth', funcLineWidth, ...
        'Color', curveColors(i,:), ...
        'DisplayName', sprintf('\\Delta T_{30} = %.1f', dT_values(i)));
end

xlabel(ax1, 'T_{eff} (°C)', ...
    'FontName',fontName, ...
    'FontSize',fontSizeLabel);

ylabel(ax1, 'Transmission rate', ...
    'FontName',fontName, ...
    'FontSize',fontSizeLabel);

text(ax1, 0.03, 0.99, '(a)', ...
    'Units','normalized', ...
    'FontName',fontName, ...
    'FontSize',fontSizePanel, ...
    'FontWeight','bold', ...
    'HorizontalAlignment','left', ...
    'VerticalAlignment','top');

legend(ax1, ...
    'Location','south', ...
    'FontName',fontName, ...
    'FontSize',fontSizeLegend, ...
    'Box','off');
ylim([0 0.2])
hold(ax1,'off');

%% =========================================================
% (b) IA beta(t)
% ==========================================================

ax2 = nexttile(tl,2);
hold(ax2,'on');

plot(ax2, date1, IAbaseline, ...
    '-', ...
    'Color', betaBaseColor, ...
    'LineWidth', 2, ...
    'DisplayName', 'UDE-inferred \beta(t)');

plot(ax2, date1, IAbeta, ...
    '-', ...
    'Color', betaFitColor, ...
    'LineWidth', 1.2, ...
    'DisplayName', 'Symbolic regression');

ylabel(ax2, 'Transmission rate', ...
    'Interpreter','tex', ...
    'FontName',fontName, ...
    'FontSize',fontSizeLabel);

text(ax2, 0.03, 0.99, '(b) IA', ...
    'Units','normalized', ...
    'FontName',fontName, ...
    'FontSize',fontSizePanel, ...
    'FontWeight','bold', ...
    'HorizontalAlignment','left', ...
    'VerticalAlignment','top');

lgdIA = legend(ax2, ...
    {'UDE-inferred', ...
     'Symbolic regression'}, ...
    'FontName',fontName, ...
    'FontSize',fontSizeLegend, ...
    'Box','off');

lgdIA.Units = 'normalized';
lgdIA.Position = [0.74 0.9 0.18 0.08];
ylim([0.5 2])
hold(ax2,'off');

%% =========================================================
% (c) IL beta(t)
% ==========================================================

ax3 = nexttile(tl,3);
hold(ax3,'on');

plot(ax3, date1, ILbaseline, ...
    '-', ...
    'Color', betaBaseColor, ...
    'LineWidth', 2);

plot(ax3, date1, ILbeta, ...
    '-', ...
    'Color', betaFitColor, ...
    'LineWidth', 1.2);

xlabel(ax3, 'Year', ...
    'FontName',fontName, ...
    'FontSize',fontSizeLabel);

ylabel(ax3, 'Transmission rate', ...
    'Interpreter','tex', ...
    'FontName',fontName, ...
    'FontSize',fontSizeLabel);
ylim([0.6 1.9])
text(ax3, 0.03, 0.99, '(c) IL', ...
    'Units','normalized', ...
    'FontName',fontName, ...
    'FontSize',fontSizePanel, ...
    'FontWeight','bold', ...
    'HorizontalAlignment','left', ...
    'VerticalAlignment','top');
lgdIL = legend(ax3, ...
    {'UDE-inferred', ...
     'Symbolic regression'}, ...
    'FontName',fontName, ...
    'FontSize',fontSizeLegend, ...
    'Box','off');

lgdIL.Units = 'normalized';
lgdIL.Position = [0.24 0.4 0.18 0.08];
hold(ax3,'off');

%% =========================================================
% (d) IN beta(t)
% ==========================================================

ax4 = nexttile(tl,4);
hold(ax4,'on');

plot(ax4, date1, INbaseline, ...
    '-', ...
    'Color', betaBaseColor, ...
    'LineWidth', 2);

plot(ax4, date1, INbeta, ...
    '-', ...
    'Color', betaFitColor, ...
    'LineWidth', 1.2);

xlabel(ax4, 'Year', ...
    'FontName',fontName, ...
    'FontSize',fontSizeLabel);

ylabel(ax4, 'Transmission rate', ...
    'Interpreter','tex', ...
    'FontName',fontName, ...
    'FontSize',fontSizeLabel);

text(ax4, 0.03, 0.99, '(d) IN', ...
    'Units','normalized', ...
    'FontName',fontName, ...
    'FontSize',fontSizePanel, ...
    'FontWeight','bold', ...
    'HorizontalAlignment','left', ...
    'VerticalAlignment','top');
lgdIN = legend(ax4, ...
    {'UDE-inferred ', ...
     'Symbolic regression'}, ...
    'FontName',fontName, ...
    'FontSize',fontSizeLegend, ...
    'Box','off');

lgdIN.Units = 'normalized';
lgdIN.Position = [0.74 0.4 0.18 0.08];
hold(ax4,'off');

%% 5. Common formatting

axAll = [ax1, ax2, ax3, ax4];

for i = 1:4
    axAll(i).FontName = fontName;
    axAll(i).FontSize = fontSizeTick;
    axAll(i).LineWidth = axisLineWidth;
    axAll(i).TickDir = 'out';
    axAll(i).Box = 'off';

    axAll(i).XGrid = 'off';
    axAll(i).YGrid = 'on';
    axAll(i).GridAlpha = 0.10;
    axAll(i).GridLineStyle = '-';
end

% format date axes
for ax = [ax2, ax3, ax4]
    ax.XLim = [date1(1), date1(end)];
    xticks(ax, yearTicks);
    xtickformat(ax, 'yyyy');
end

% remove top-right x tick labels to keep compact layout
ax2.XTickLabel = [];

%% 6. Export

drawnow;

exportgraphics(fig, ...
    'Figure_symbolic_function_beta.eps', ...
    'ContentType','vector', ...
    'BackgroundColor','white');